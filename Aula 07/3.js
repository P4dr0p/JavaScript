const numeros = [10, 20, 30];

// push(): adiciona no final do array
numeros.push(40);
console.log(numeros);

// unshift(): adiciona no início do array
numeros.unshift(0);
console.log(numeros);

// pop(): remove no final do array
numeros.pop();
console.log(numeros);

// shift(): remove no início do array
numeros.shift();
console.log(numeros);